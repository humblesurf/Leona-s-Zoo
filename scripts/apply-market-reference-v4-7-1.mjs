import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire('C:/Users/XTIA/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const sharp=require('sharp'),context={window:{}};
vm.runInNewContext(fs.readFileSync('geo/assets/game-data.js','utf8'),context);
const {GAME_DIALOGUE:dialogue,GAME_SCENES:scenes,GAME_SCENE_ORDER:order}=context.window;
const before=JSON.stringify(Object.fromEntries(Object.entries(scenes).filter(([id])=>id!=='market')));
const image='geo/assets/bg/market-preferred-v4-7-1.png',background='assets/bg/market-preferred-v4-7-1.webp';
await sharp(image).webp({lossless:true,effort:6}).toFile('geo/'+background);
const metadata=await sharp(image).metadata();
assert.equal(metadata.width/metadata.height,3);
const centres=[.067,.208,.352,.495,.639,.788,.930];
const market=scenes.market;
Object.assign(market,{bgStrip:background,bgAspect:3,bgMirror:false,panorama:true});
market.animals.forEach((a,i)=>Object.assign(a,{u:centres[i],feetY:.73,h:.36,idle:'none',basketHotspot:{width:.136,top:.245,height:.52}}));
assert.equal(before,JSON.stringify(Object.fromEntries(Object.entries(scenes).filter(([id])=>id!=='market'))));
fs.writeFileSync('geo/assets/game-data.js','/* V4.7.1: selected eye-level market background; other scenes use V4.7. */\nwindow.GAME_DIALOGUE = '+JSON.stringify(dialogue)+';\nwindow.GAME_SCENES = '+JSON.stringify(scenes)+';\nwindow.GAME_SCENE_ORDER = '+JSON.stringify(order)+';\n');
fs.writeFileSync('geo/assets/placements.json',JSON.stringify(scenes,null,2));
const manifest={version:'V4.7.1',background,source:'assets/bg/market-preferred-v4-7-1.png',size:[metadata.width,metadata.height],encoding:'lossless WebP',sha256:crypto.createHash('sha256').update(fs.readFileSync('geo/'+background)).digest('hex'),reference:'User-selected eye-level wooden fruit stand, full wicker baskets, no people.',edit:'Only baskets six and seven changed to tomatoes and carrots to match the existing introductions.',layout:'One panorama at its natural 3:1 ratio, no mirrored or repeated baskets. Basket-aligned interaction; opening fruit appears only when activated.',unchanged:'V4.7 quadruped art, animation renderer, other scenes, all existing narration and audio.'};
fs.writeFileSync('geo/assets/market-v4-7-1/manifest.json',JSON.stringify(manifest,null,2));
